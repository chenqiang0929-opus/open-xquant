def sheet(wb, name, cols, egrow=None):
    ws = wb.create_sheet(name)
    for c, (h, req, tip, wd) in enumerate(cols, 1):
        x = ws.cell(1, c, h)
        x.fill, x.font = NAVY, HF
        x.alignment = Alignment("center", "center", wrap_text=True)
        y = ws.cell(2, c, f"{req}｜{tip}")
        y.fill = REQ if req == "必填" else OPT
        y.font = Font(size=8, color="7F7F7F")
        y.alignment = Alignment("left", "top", wrap_text=True)
        y.border = THIN
        ws.column_dimensions[get_column_letter(c)].width = wd
    ws.row_dimensions[2].height = 42
    if egrow:
        for c, v in enumerate(egrow, 1):
            z = ws.cell(3, c, v)
            z.fill, z.border = EG, THIN
            z.font = Font(size=9, italic=True, color="808080")
            z.alignment = Alignment("center", "center")
    ws.freeze_panes = "A3"
    return ws


