"""生成「交易尸检」录入模板 —— 两张表:有流水的填 A,只记得大概的填 B。

用法
----
    uv run python rps_pool_study/trade_autopsy_template.py
    → /home/user/oxq-panel/交易复盘_录入模板.xlsx

设计原则
--------
**只让人填机器算不出来的东西。** 券商对账单能导出的(日期/代码/买卖/价格/数量/费用)
照抄即可;RPS、距均线、周线状态、市场广度、行业、同期同类对照、卖出后又涨多少 ——
这些全部由 `trade_autopsy.py` 从面板自动补全,不需要你回忆。

**买入理由这类主观项放在第二遍。** 第一遍先跑出配对好的「回合表」,
你对着回合表填「当时为什么买」,比对着流水凭空回忆准确得多。

**A 表(精确流水)和 B 表(记忆清单)分开统计,绝不混。** 原因是记忆有系统性偏差:
人记得住大亏和大赚,记不住小额和平淡的 —— 混在一起会让样本偏向极端,
并且**严重低估交易次数**,于是「过度交易」和「手续费侵蚀」这两条根本查不出来。
B 表能回答「哪类股票/哪种买点亏钱」,**不能**回答「我是不是交易太频繁」。

**本文件不构成任何投资建议。**
"""

